"""External pre-deadline strength sources -> pairwise P(T1 beats T2), T1 < T2 Kaggle IDs.

Every loader returns a DataFrame[T1, T2, p, d] for all pairs of that season's seeded teams
(d = raw rating difference T1 - T2 on the source's own scale; p = probability).  `source(name, year, g)`
dispatches; `available()` lists (name, year, gender).  See kaggle_tuning/EXT_SOURCES.md for provenance.

Probability mapping is a no-intercept logistic p = sigmoid(k * d).  k is fitted WALK-FORWARD: only on the
tournaments of earlier seasons for which the same source exists (K0 prior when there are none), so a
standalone score for year Y never uses Y's results.  Pass `k=` to override.

Raw data lives outside the repo (gitignored) in <MANIA_DATA>/../ext_*; see PATHS below.
"""
