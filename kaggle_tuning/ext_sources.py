FUT_DIR = ROOT / "ext_futures" / "raw"
# (file, snapshot as archived on web.archive.org UTC, original url). Tournament teams were already announced.
FUT_FILES = {
    2021: ("vi20210316.html", "2021-03-16 22:46", "vegasinsider.com/college-basketball/odds/futures/"),
    2022: ("vi20220317.html", "2022-03-17 03:46", "vegasinsider.com/college-basketball/odds/futures/"),
    2023: ("vi20230313.html", "2023-03-13 23:40", "vegasinsider.com/college-basketball/odds/futures/"),
    2024: ("so20240319.html", "2024-03-19 17:32", "scoresandodds.com/ncaab/futures"),
}


def _html_text(f) -> str:
    b = open(f, "rb").read()
    try:
        b = gzip.decompress(b)
    except Exception:
        pass
    s = b.decode("utf-8", "ignore")
    t = re.sub(r"<script.*?</script>|<style.*?</style>", "", s, flags=re.S)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", t)).replace("&amp;", "&").replace("&apos;", "'").replace("&#8217;", "'")


def _prob(american: float) -> float:
    return 100 / (american + 100) if american > 0 else -american / (-american + 100)


def _parse_pairs(seg: str) -> list[tuple[str, float]]:
    return [(m.group(1).strip(), float(m.group(2))) for m in re.finditer(r"([A-Za-z][A-Za-z&.' \-\(\)]*?) ([+-]\d{3,6})(?= |$)", seg)]


def futures_raw(year: int, g: str) -> list[tuple[str, float]]:
    """[(team name, implied prob incl. vig)] of championship futures published before the deadline."""
    f = FUT_DIR / FUT_FILES[year][0]
    if year == 2021 and g == "M":
        t = _html_text(f)
        i = t.find("Odds To Win 2021 National Championship")
        j = t.find("2021 NCAA Tournament Regional Odds")
        pr = _parse_pairs(t[i:j].split("Fractional", 1)[1])
        return [(n, _prob(o)) for n, o in pr]
    if year == 2023:
        t = _html_text(f)
        key = {"M": "2023 NCAA Men's Tournament Opening Odds", "W": "2023 NCAA Women's Tournament Opening Odds"}[g]
        i = t.find(key) + len(key)
        j = t.find(" MARCH MADNESS BETTING RESOURCES", i) if g == "M" else len(t)
        seg = t[i:j]
        if g == "W":
            seg = seg[: seg.find(" MARCH MADNESS") if " MARCH MADNESS" in seg else len(seg)]
        return [(n, _prob(o)) for n, o in _parse_pairs(seg)]
    if year == 2022 and g == "M":
        s = open(f, errors="ignore").read()
        names = re.findall(r'd-lg-block d-none">\s*<!--t\.[\d.]+-->\s*([^<]+?)\s*</span>', s)
        names = [n.replace("&apos;", "'").replace("&amp;", "&") for n in names]
        t = _html_text(f)
        i = t.find("Gonzaga Bulldogs GNZG")
        seg = t[i: t.find("Create your free VegasInsider")]
        runs, cur = [], []
        for x in re.findall(r"[+-]\d+|N/A", seg):
            if x == "N/A":
                if cur:
                    runs.append(cur)
                cur = []
            else:
                cur.append(float(x))
        runs.append(cur) if cur else None
        runs = [r for r in runs if len(r) == len(names)]
        pr = np.mean([[_prob(o) for o in r] for r in runs], axis=0)  # two books, averaged in probability
        return list(zip(names, pr))
    if year == 2024 and g == "M":
        t = _html_text(f)
        out = []
        for seg in t.split("'> ")[1:]:
            m = re.match(r"([A-Za-z][A-Za-z&.' \-]*?)(?: \(\d+\))? \d+-\d+ (.*)", seg)
            if not m:
                continue
            odds = [float(x) for x in re.findall(r"[+-]\d{3,6}", m.group(2)[:120].split("'>")[0])]
            if odds:
                out.append((m.group(1), float(np.mean([_prob(o) for o in odds]))))
        return out
    raise KeyError((year, g))


