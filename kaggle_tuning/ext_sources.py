CLOSING_DIR = ROOT / "ext_market" / "closing"


@lru_cache(maxsize=None)
def r64_moneylines(year: int) -> pd.DataFrame:
    """T1,T2,p,n for men's round-of-64 games that have >=1 bookmaker moneyline whose `last_update_utc` is BEFORE
    00:00 UTC of the first round-of-64 day (i.e. a quote that already existed by Wednesday evening ET, so before any
    Kaggle deadline).  Source: Kaggle 'archangel0x01/march-madness-results-and-closing-odds' (ext_market/closing).
    Each book's quote is vig-removed (proportional) and the books averaged in probability.  Coverage is partial
    (about 10-25 of 32 games per year; only ~1-4 quotes per game) and the quotes may be stale."""
    g = pd.read_csv(CLOSING_DIR / "games.csv")
    o = pd.read_csv(CLOSING_DIR / "closing_odds.csv")
    g = g[(g.competition == "NCAA Men") & (g["round"] == "1/32-finals") & (g.season == f"{year - 1}-{str(year)[2:]}")]
    cut = pd.Timestamp(g.date.min()).tz_localize("UTC")
    o = o[o.game_id.isin(g.game_id)].assign(t=lambda d: pd.to_datetime(d.last_update_utc))
    o = o[o.t < cut]
    o = o.assign(ph=lambda d: (1 / d.home_odds) / (1 / d.home_odds + 1 / d.away_odds))
    q = o.groupby("game_id").ph.agg(["mean", "size"])
    rows = []
    for r in g.itertuples():
        if r.game_id not in q.index:
            continue
        a, b = team_id(r.home_team, "M"), team_id(r.away_team, "M")
        if a is None or b is None:
            continue
        ph = q.loc[r.game_id, "mean"]
        if a < b:
            rows.append((a, b, ph, int(q.loc[r.game_id, "size"])))
        else:
            rows.append((b, a, 1 - ph, int(q.loc[r.game_id, "size"])))
    return pd.DataFrame(rows, columns=["T1", "T2", "p", "n"])


