@lru_cache(maxsize=None)
def torvik_ratings(year: int) -> pd.DataFrame:
    """T-Rank as of Selection Sunday. Source: https://barttorvik.com/timemachine/team_results/<date>_team_results.json.gz
    (adjoe=col4, adjde=col6, barthag=col8).  HTTP last-modified: 2021-24 files are stamped the Monday 15:30 UTC after the
    snapshot date (i.e. generated long before the Thursday deadline); 2015-19 files were regenerated by Torvik in
    Sep-Nov 2019 (as-of-date recomputation from games on/before that date; records match Selection Sunday, e.g.
    2015 Kentucky 34-0, 2018 Virginia 31-2)."""
    f = TORVIK_DIR / f"{SELECTION_SUNDAY[year]}.gz"
    rows = json.load(gzip.open(f))
    out = []
    for r in rows:
        tid = team_id(r[1], "M")
        if tid is not None:
            out.append((tid, r[1], r[4], r[6], r[8]))
    d = pd.DataFrame(out, columns=["TeamID", "name", "adjoe", "adjde", "barthag"]).drop_duplicates("TeamID")
    d["adjem"] = d.adjoe - d.adjde
    return d.set_index("TeamID")


def _torvik_d(year: int, how: str) -> pd.DataFrame:
    t = torvik_ratings(year)
    if how == "barthag":  # log5 in log-odds space: logit(barthag) difference
        b = t.barthag.clip(1e-6, 1 - 1e-6)
        r = np.log(b / (1 - b))
    else:
        r = t.adjem
    return all_pairs(r, year, "M")


