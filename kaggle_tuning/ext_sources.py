def _nz(x: str) -> str:
    return re.sub(r"[^a-z0-9&]+", " ", str(x).lower().replace(".", "").replace("'", "")).strip()


@lru_cache(maxsize=None)
def _spell(g: str) -> dict:
    sp = pd.read_csv(DATA / f"{g}TeamSpellings.csv", encoding="cp1252")
    m = {_nz(s): t for s, t in zip(sp.TeamNameSpelling, sp.TeamID)}
    tn = pd.read_csv(DATA / f"{g}Teams.csv")
    m.update({_nz(s): t for s, t in zip(tn.TeamName, tn.TeamID)})
    return m


def team_id(name: str, g: str) -> int | None:
    m = _spell(g)
    k = _nz(name)
    return m.get(k, m.get(_ALIAS.get(k, k), m.get(k.replace("st", "state") if k.endswith(" st") else k)))


def seeded(year: int, g: str) -> list[int]:
    return sorted(read(f"{g}NCAATourneySeeds").query("Season == @year").TeamID)


def all_pairs(r: pd.Series, year: int, g: str) -> pd.DataFrame:
    """r: rating indexed by TeamID. All pairs of seeded teams that have a rating, T1 < T2."""
    ids = [t for t in seeded(year, g) if t in r.index and pd.notna(r[t])]
    a, b = np.triu_indices(len(ids), 1)
    ids = np.array(ids)
    return pd.DataFrame({"T1": ids[a], "T2": ids[b], "d": r[ids[a]].values - r[ids[b]].values})


def results(g: str, year: int) -> pd.DataFrame:
    """Played tournament games (First Four included, as in backtest.test_pairs): Season, T1<T2, y."""
    from . import backtest as B
    return B.test_pairs(g, year)


